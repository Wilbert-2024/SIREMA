CREATE DEFINER=`root`@`localhost` PROCEDURE `filtro_habilitar_carrera_centro`(
in carreraId int,
in centroId int
)
BEGIN
set @existe = 0;
set @estado = 0;

/*
Verificar si existe registro del centro y carrera
*/
SELECT @existe := count(*) FROM sirema.carrera_centro
where Centro_Id = centroId and Carrera_Id = carreraId;

/*Si existe el registro*/
if @existe > 0 then
	/*Conseguir el Estado invertido del mismo
    Si el Estado actual es 0, 
    entonces devuelve 1, 
    si es 1 devuelte 0
    */
	select @estado :=if(Estado =0, 1, 0) from carrera_centro
	where Centro_Id = centroId and Carrera_Id = carreraId;
    
    /*Actualizar el estado del registro
    * solo si estaba Deshabilitado
    */
    if @estado = 1 then
		update
		carrera_centro
		set 
		Estado = @estado
		where
		Centro_Id = centroId 
		and 
		Carrera_Id = carreraId;
	end if;
/*
 Si el registro no existe,
 entonces se crea uno nuevo
*/
else
	insert into
    carrera_centro
    (Centro_Id, Carrera_Id)
    values
    (centroId, carreraId);
end if;

END ;;
